import turtle

turtle.shape("turtle")

turtle.teleport(-50, 0)
turtle.right(90)
turtle.circle(50, 180)

turtle.teleport(-40, 40)
turtle.circle(-10, 180)

turtle.teleport(40, 40)
turtle.setheading(90)
turtle.circle(10, 180)

turtle.teleport(0, 100)
turtle.setheading(0)
turtle.circle(-100)

turtle.hideturtle()
turtle.done()
